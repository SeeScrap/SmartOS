#!/usr/bin/env python3
"""Generates src/gfx/font5x8.h from tools/font5x8.txt.

    python tools/gen_font.py                 # validate + write the header
    python tools/gen_font.py --preview TEXT  # also print TEXT as the panel will

The text file is the source of truth; the header is output and says so. The
point of the split is review: 95 glyphs as hex bytes cannot be checked by eye,
95 glyphs as pictures can.

Validation is deliberately fussy. Every rule below exists because breaking it
would not fail to compile - it would draw a slightly wrong letter, which is the
kind of bug nobody notices until a screenshot.
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "font5x8.txt"
OUT = HERE.parent / "src" / "gfx" / "font5x8.h"

W, H = 5, 8
FIRST, LAST = 32, 126
NAMES = {"space": " ", "backslash": "\\"}

# Only these may put ink on row 7, the descender row. Anything else there is a
# glyph drawn one row too low.
DESCENDERS = set("gjpqy,;")


def fail(msg):
    sys.exit(f"gen_font: {msg}")


def parse():
    glyphs = {}
    current = None
    rows = []

    def close(lineno):
        if current is None:
            return
        if len(rows) != H:
            fail(f"'{current}' has {len(rows)} rows, expected {H} (near line {lineno})")
        glyphs[current] = rows[:]

    for lineno, raw in enumerate(SRC.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.rstrip()
        # A comment is "#" alone or "# ..."; a pixel row is exactly five of
        # '#' and '.', so "#####" can never be mistaken for one.
        if not line or line == "#" or line.startswith("# "):
            continue
        if line.startswith("= "):
            close(lineno)
            name = line[2:]
            ch = NAMES.get(name, name)
            if len(ch) != 1:
                fail(f"line {lineno}: bad glyph name {name!r}")
            if ch in glyphs:
                fail(f"line {lineno}: '{ch}' defined twice")
            current, rows = ch, []
            continue
        if current is None:
            fail(f"line {lineno}: pixel row before any '= <char>' header")
        if len(line) != W or not set(line) <= set("#."):
            fail(f"line {lineno}: '{current}' row {len(rows)} is {line!r}; "
                 f"want {W} chars of '#' and '.'")
        rows.append(line)
    close("EOF")
    return glyphs


def check(glyphs):
    want = {chr(c) for c in range(FIRST, LAST + 1)}
    missing = sorted(want - glyphs.keys())
    extra = sorted(glyphs.keys() - want)
    if missing:
        fail(f"missing glyphs: {''.join(missing)!r}")
    if extra:
        fail(f"glyphs outside {FIRST}..{LAST}: {''.join(extra)!r}")

    for ch, rows in glyphs.items():
        if "#" in rows[7] and ch not in DESCENDERS:
            fail(f"'{ch}' has ink on the descender row but is not a descender")
        if ch != " " and all(r == "....." for r in rows):
            fail(f"'{ch}' is blank")


def encode(rows):
    # bit 4 = leftmost column, so the renderer tests (0x10 >> col).
    return [int(r.replace("#", "1").replace(".", "0"), 2) for r in rows]


def write(glyphs):
    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// GENERATED by tools/gen_font.py from tools/font5x8.txt - do not edit.",
        "// Change the pictures in the .txt and re-run the script instead.",
        "//",
        f"// {LAST - FIRST + 1} glyphs, ASCII {FIRST}..{LAST}. One byte per row, {H} rows",
        "// per glyph; bit 4 is the leftmost of the five columns.",
        "",
        f"#define FONT5X8_FIRST  {FIRST}",
        f"#define FONT5X8_LAST   {LAST}",
        f"#define FONT5X8_W      {W}",
        f"#define FONT5X8_H      {H}",
        "",
        f"static const uint8_t font5x8[{LAST - FIRST + 1}][{H}] = {{",
    ]
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        bytes_ = ", ".join(f"0x{b:02X}" for b in encode(glyphs[ch]))
        label = {"\\": "backslash", " ": "space"}.get(ch, ch)
        lines.append(f"    {{ {bytes_} }},   // {c:3d} {label}")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def preview(glyphs, text):
    for row in range(H):
        out = []
        for ch in text:
            g = glyphs.get(ch, glyphs["?"])
            out.append(g[row].replace(".", " ") + " ")
        print("".join(out).rstrip())


def main():
    glyphs = parse()
    check(glyphs)
    write(glyphs)
    print(f"gen_font: {len(glyphs)} glyphs OK -> {OUT.relative_to(HERE.parent)}")
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        preview(glyphs, " ".join(sys.argv[2:]))


if __name__ == "__main__":
    main()
